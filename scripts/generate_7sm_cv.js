// แปลงเป็น format ที่ CV_DATA.json ใช้: { gender: { age: { year: value } } }
function buildCVStructure(data) {
  const result = {};
  for (const [age, years] of Object.entries(data)) {
    result[age] = {};
    years.forEach((val, i) => {
      result[age][(i + 1).toString()] = val;
    });
  }
  return result;
}

