// ── long-press handler ─────────────────────────────────────────────────────────
window._attachDiseaseHold = function(containerEl) {
    if (!containerEl || containerEl.dataset.holdReady) return;
    containerEl.dataset.holdReady = '1';
    containerEl.querySelectorAll(':scope > div').forEach(row => {
        if (row.dataset.holdReady) return;
        row.dataset.holdReady = '1';

        // หา disease name จาก text content ของ <p> แรก
        const pEl = row.querySelector('p');
        if (!pEl) return;
        const rawName = pEl.textContent.replace(/^\s*\d+[\)\.]\s*/, '').trim();
        // lookup
        let def = null;
        for (const key of Object.keys(window._CX_DEF_MAP)) {
            if (rawName.includes(key) || key.includes(rawName)) { def = window._CX_DEF_MAP[key]; break; }
        }
        if (!def) {
            // fallback: partial match
            for (const [key, val] of Object.entries(window._CX_DEF_MAP)) {
                const short = rawName.slice(0, 10);
                if (key.startsWith(short)) { def = val; break; }
            }
        }
        if (!def) return;

        // เพิ่ม hint icon ถ้ายังไม่มี
        if (!row.querySelector('._defHint')) {
            const hint = document.createElement('span');
            hint.className = '_defHint';
            hint.innerHTML = ' <i class="fas fa-book-open" style="font-size:9px;color:#93c5fd;opacity:0.7;vertical-align:middle;" title="กดค้างเพื่อดูคำนิยาม"></i>';
            if (pEl) pEl.appendChild(hint);
        }

        const showDef = () => {
            if (typeof Swal !== 'undefined') {
                Swal.fire({
                    title: `<span style="font-family:Kanit,sans-serif;font-size:14px;color:#1e40af;line-height:1.4;">${rawName}</span>`,
                    html: `<div style="font-family:Kanit,sans-serif;font-size:13px;color:#334155;line-height:1.8;text-align:left;padding:4px 0;">${def}</div>`,
                    showConfirmButton: false,
                    showCloseButton: true,
                    width: Math.min(window.innerWidth - 24, 420),
                    didOpen: () => { const p = Swal.getPopup(); if (p) p.style.borderRadius = '20px'; }
                });
            }
        };

        // Long-press: mouse
        let _timer = null;
        row.addEventListener('mousedown', () => { _timer = setTimeout(showDef, 500); });
        row.addEventListener('mouseup',   () => { clearTimeout(_timer); });
        row.addEventListener('mouseleave',() => { clearTimeout(_timer); });

        // Long-press: touch
        let _tTimer = null;
        row.addEventListener('touchstart', e => {
            _tTimer = setTimeout(() => { e.preventDefault(); showDef(); }, 500);
        }, { passive: false });
        row.addEventListener('touchend',    () => clearTimeout(_tTimer));
        row.addEventListener('touchcancel', () => clearTimeout(_tTimer));
        row.addEventListener('touchmove',   () => clearTimeout(_tTimer));

        row.style.cursor = 'pointer';
    });
};

// init เมื่อ modal เปิด — hook เข้า openPopup
(function() {
    const _orig = window.openPopup;
    window.openPopup = function(id) {
        if (typeof _orig === 'function') _orig(id);
        const modalContainerMap = {
            'disease15Modal': '#disease15Modal .overflow-y-auto',
            'disease5Modal':  '#disease5Modal .overflow-y-auto',
            'disease45Modal': '#disease45Modal .overflow-y-auto',
        };
        if (modalContainerMap[id]) {
            setTimeout(() => {
                const el = document.querySelector(modalContainerMap[id]);
                if (el) window._attachDiseaseHold(el);
            }, 80);
        }
    };
})();
